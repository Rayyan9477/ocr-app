#!/usr/bin/env node
/**
 * Setup Tesseract Language Data
 * Downloads and configures Tesseract.js language training data for offline use
 */

import { writeFile, mkdir } from 'fs/promises';
import { existsSync } from 'fs';
import { join } from 'path';
import https from 'https';
import { createWriteStream } from 'fs';

const TESSDATA_URL = 'https://tessdata.projectnaptha.com/4.0.0/';
const LANGUAGES = ['eng']; // Add more languages as needed: 'fra', 'deu', 'spa', etc.
const PUBLIC_DIR = join(process.cwd(), 'public', 'tessdata');

console.log('='.repeat(70));
console.log('Tesseract Language Data Setup');
console.log('='.repeat(70));
console.log('');

// Create public/tessdata directory if it doesn't exist
if (!existsSync(PUBLIC_DIR)) {
  await mkdir(PUBLIC_DIR, { recursive: true });
  console.log(`✓ Created directory: ${PUBLIC_DIR}`);
}

async function downloadFile(url, dest) {
  return new Promise((resolve, reject) => {
    const file = createWriteStream(dest);
    https.get(url, (response) => {
      if (response.statusCode !== 200) {
        reject(new Error(`Failed to download: ${response.statusCode}`));
        return;
      }

      response.pipe(file);

      file.on('finish', () => {
        file.close();
        resolve();
      });
    }).on('error', (err) => {
      file.close();
      reject(err);
    });
  });
}

// Download language training data files
console.log(`\nDownloading language training data for: ${LANGUAGES.join(', ')}\n`);

for (const lang of LANGUAGES) {
  const filename = `${lang}.traineddata.gz`;
  const url = `${TESSDATA_URL}${filename}`;
  const dest = join(PUBLIC_DIR, filename);

  if (existsSync(dest)) {
    console.log(`⊘ ${lang}: Already exists, skipping...`);
    continue;
  }

  try {
    process.stdout.write(`⬇ ${lang}: Downloading...`);
    await downloadFile(url, dest);
    console.log(' ✓ Done');
  } catch (error) {
    console.log(` ✗ Failed: ${error.message}`);
  }
}

// Create configuration file
const configContent = `/**
 * Tesseract.js Configuration
 * Auto-generated by setup-tessdata.mjs
 */

export const TESSDATA_CONFIG = {
  // Use local language data files instead of CDN
  langPath: '/tessdata',

  // Available languages (add more as needed)
  languages: ${JSON.stringify(LANGUAGES, null, 2)},

  // Cache settings
  cacheMethod: 'write', // Options: 'write', 'refresh', 'none'

  // Worker settings
  workerPath: undefined, // Use default worker
  corePath: undefined,   // Use default core
};

export default TESSDATA_CONFIG;
`;

const configPath = join(process.cwd(), 'lib', 'tessdata-config.ts');
await writeFile(configPath, configContent);
console.log(`\n✓ Created configuration: lib/tessdata-config.ts`);

console.log('\n' + '='.repeat(70));
console.log('✓ Setup Complete!');
console.log('='.repeat(70));
console.log('\nNext steps:');
console.log('1. Update lib/simple-ocr-service.ts to use local language data');
console.log('2. Import TESSDATA_CONFIG and pass langPath to createWorker()');
console.log('3. Test OCR functionality without internet connection');
console.log('\nLanguage files location: public/tessdata/');
console.log('Configuration file: lib/tessdata-config.ts');
console.log('');
